<?php

use Cose\Algorithms;
use Webauthn\AttestationStatement\AttestationStatementSupportManager;
use Webauthn\AttestationStatement\NoneAttestationStatementSupport;
use Webauthn\AuthenticatorAssertionResponse;
use Webauthn\AuthenticatorAssertionResponseValidator;
use Webauthn\AuthenticatorAttestationResponse;
use Webauthn\AuthenticatorAttestationResponseValidator;
use Webauthn\AuthenticatorSelectionCriteria;
use Webauthn\CeremonyStep\CeremonyStepManagerFactory;
use Webauthn\Denormalizer\WebauthnSerializerFactory;
use Webauthn\PublicKeyCredential;
use Webauthn\PublicKeyCredentialCreationOptions;
use Webauthn\PublicKeyCredentialParameters;
use Webauthn\PublicKeyCredentialRequestOptions;
use Webauthn\PublicKeyCredentialRpEntity;
use Webauthn\PublicKeyCredentialUserEntity;

/**
 * Passkeys (WebAuthn/FIDO2) support for operators
 *
 * Registration and authentication ceremonies are validated by web-auth/webauthn-lib.
 * Only the relying party configuration and the credential storage are provided here.
 */
class erLhcoreClassUserPasskey
{
    /**
     * Session key holding options of the ongoing registration ceremony
     */
    const SESSION_REGISTRATION = 'lhc_passkey_registration';

    /**
     * Session key holding options of the ongoing authentication ceremony
     */
    const SESSION_AUTHENTICATION = 'lhc_passkey_authentication';

    /**
     * How long (seconds) options generated by us are valid
     */
    const OPTIONS_TTL = 300;

    /**
     * Ceremony timeout in milliseconds passed to the browser
     */
    const CEREMONY_TIMEOUT = 60000;

    /**
     * How many passkeys a single operator can have
     */
    const MAX_PASSKEYS_PER_USER = 10;

    /**
     * Passkeys requires webauthn library to be installed via composer
     */
    public static function isAvailable()
    {
        return class_exists('\Webauthn\PublicKeyCredentialCreationOptions');
    }

    /**
     * Passkeys are available for user and enabled in configuration
     */
    public static function isEnabled()
    {
        if (self::isAvailable() == false) {
            return false;
        }

        $configuration = self::getConfiguration();

        return isset($configuration['enabled']) && $configuration['enabled'] == 1;
    }

    /**
     * Passkeys configuration. Stored in `lh_chat_config` as `passkey_options`
     *
     * - enabled - 1|0 is passkeys enabled, default 1
     * - rp_id - relying party ID, default is current host name
     * - rp_name - relying party name shown by the browser, default is current host name
     * - secured_rp_ids - comma separated list of RP IDs allowed to work over plain HTTP
     */
    public static function getConfiguration()
    {
        static $configuration = null;

        if ($configuration === null) {
            $configuration = (array)erLhcoreClassModelChatConfig::fetch('passkey_options')->data;
        }

        return $configuration;
    }

    /**
     * Relying party ID (domain name without scheme and port)
     */
    public static function getRpId()
    {
        $configuration = self::getConfiguration();

        if (isset($configuration['rp_id']) && trim($configuration['rp_id']) != '') {
            return trim($configuration['rp_id']);
        }

        return self::getDetectedHost();
    }

    /**
     * Host name of the current request. Used as a default relying party ID and name
     */
    public static function getDetectedHost()
    {
        $host = parse_url((string)erLhcoreClassSystem::getHost(), PHP_URL_HOST);

        return $host != '' && $host !== false ? $host : 'localhost';
    }

    /**
     * Relying party name displayed by the browser
     */
    public static function getRpName()
    {
        $configuration = self::getConfiguration();

        if (isset($configuration['rp_name']) && trim($configuration['rp_name']) != '') {
            return trim($configuration['rp_name']);
        }

        return self::getRpId();
    }

    /**
     * Origins which are allowed to be used without HTTPS.
     * Local development hosts are always allowed, additional ones can be defined in configuration
     */
    public static function getSecuredRelyingPartyIds()
    {
        $securedIds = array();

        $rpId = self::getRpId();

        if (in_array($rpId, array('localhost', '127.0.0.1', '::1'), true)) {
            $securedIds[] = $rpId;
        }

        $configuration = self::getConfiguration();

        if (isset($configuration['secured_rp_ids']) && $configuration['secured_rp_ids'] != '') {
            foreach (explode(',', $configuration['secured_rp_ids']) as $securedId) {
                $securedId = trim($securedId);

                if ($securedId == '') {
                    continue;
                }

                // Only relying party ID is expected, but tolerate a full origin or a port being entered
                if (strpos($securedId, '://') !== false) {
                    $securedId = (string)parse_url($securedId, PHP_URL_HOST);
                } else {
                    $securedId = preg_replace('/:\d+$/', '', $securedId);
                }

                if ($securedId != '') {
                    $securedIds[] = $securedId;
                }
            }
        }

        return array_values(array_unique($securedIds));
    }

    public static function base64UrlEncode($data)
    {
        return rtrim(strtr(base64_encode($data), '+/', '-_'), '=');
    }

    public static function base64UrlDecode($data)
    {
        return base64_decode(strtr($data, '-_', '+/'));
    }

    /**
     * Opaque, stable and non personal user handle. Browsers require it to be max 64 bytes long
     */
    public static function getUserHandle($user)
    {
        $secretHash = erConfigClassLhConfig::getInstance()->getSetting('site', 'secrethash');

        return hash_hmac('sha256', 'lhc_passkey_user_' . (int)$user->id, (string)$secretHash, true);
    }

    /**
     * @return \Symfony\Component\Serializer\SerializerInterface
     */
    public static function getSerializer()
    {
        static $serializer = null;

        if ($serializer === null) {
            $attestationStatementSupportManager = new AttestationStatementSupportManager(array(
                new NoneAttestationStatementSupport()
            ));

            $serializer = (new WebauthnSerializerFactory($attestationStatementSupportManager))->create();
        }

        return $serializer;
    }

    public static function getCeremonyStepManagerFactory()
    {
        static $ceremonyStepManagerFactory = null;

        if ($ceremonyStepManagerFactory === null) {
            $ceremonyStepManagerFactory = new CeremonyStepManagerFactory();

            $securedRelyingPartyIds = self::getSecuredRelyingPartyIds();

            if (!empty($securedRelyingPartyIds)) {
                $ceremonyStepManagerFactory->setSecuredRelyingPartyId($securedRelyingPartyIds);
            }
        }

        return $ceremonyStepManagerFactory;
    }

    /**
     * Passkeys assigned to the user
     *
     * @return erLhcoreClassModelUserPasskey[]
     */
    public static function getPasskeyList($userId)
    {
        return erLhcoreClassModelUserPasskey::getList(array(
            'filter' => array('user_id' => (int)$userId),
            'sort' => 'id ASC',
            'limit' => false
        ));
    }

    /**
     * Already registered credentials which should not be registered again
     *
     * @return \Webauthn\PublicKeyCredentialDescriptor[]
     */
    public static function getCredentialDescriptors($userId)
    {
        $descriptors = array();

        foreach (self::getPasskeyList($userId) as $passkey) {
            try {
                $descriptors[] = $passkey->getPublicKeyCredentialDescriptor();
            } catch (Exception $e) {
                erLhcoreClassLog::write('Passkey ' . $passkey->id . ' could not be decoded - ' . $e->getMessage());
            }
        }

        return $descriptors;
    }

    public static function sanitizeName($name)
    {
        $name = trim(strip_tags((string)$name));

        return function_exists('mb_substr') ? mb_substr($name, 0, 100) : substr($name, 0, 100);
    }

    /**
     * Human readable authenticator type. Derived from the credential data stored during registration
     *
     * @param string $credential JSON serialized \Webauthn\CredentialRecord
     * @param string $aaguid
     * @return string
     */
    public static function getAuthenticatorType($credential, $aaguid = '')
    {
        $t = function ($text) {
            return erTranslationClassLhTranslation::getInstance()->getTranslation('user/passkey', $text);
        };

        $credentialData = json_decode((string)$credential, true);

        if (!is_array($credentialData)) {
            return $t('Unknown authenticator');
        }

        $transports = isset($credentialData['transports']) && is_array($credentialData['transports']) ? $credentialData['transports'] : array();

        if ($aaguid == '' && isset($credentialData['aaguid'])) {
            $aaguid = (string)$credentialData['aaguid'];
        }

        // Well known authenticators, everything else is described by its transports
        $knownAuthenticators = array(
            'ea9b8d66-4d01-1d21-3ce4-b6b48cb575d4' => 'Google Password Manager',
            'fbfc3007-154e-4ecc-8c0b-6e020557d7bd' => 'Apple iCloud Keychain',
            '08987058-cadc-4b81-b6e1-30de50dcbe96' => 'Windows Hello',
            '9ddd1817-af5a-4672-a2b9-3e3dd95000a9' => 'Windows Hello',
            '6028b017-b1d4-4c02-b4b3-afcdafc96bb2' => 'Windows Hello',
            'bada5566-a7aa-401f-bd96-45619a55120d' => '1Password',
            'd548826e-79b4-db40-a3d8-11116f7e8349' => 'Bitwarden',
            '531126d6-e717-415c-9320-3d9aa6981239' => 'Dashlane',
            'b84e4048-15dc-4dd0-8640-f4f60813c8af' => 'NordPass',
            '0ea242b4-43c4-4a1b-8b17-dd6d0b6baec6' => 'Keeper',
            'f3809540-7f14-49c1-a8b3-8f813b225541' => 'Enpass',
        );

        $aaguid = strtolower(trim((string)$aaguid));

        if (isset($knownAuthenticators[$aaguid])) {
            $type = $knownAuthenticators[$aaguid];
        } elseif (in_array('hybrid', $transports, true)) {
            $type = $t('Phone or tablet');
        } elseif (in_array('internal', $transports, true)) {
            $type = $t('Device passkey');
        } elseif (count(array_intersect($transports, array('usb', 'nfc', 'ble', 'smart-card'))) > 0) {
            $type = $t('Security key');
        } else {
            $type = $t('Unknown authenticator');
        }

        if (isset($credentialData['backupStatus'])) {
            $isSynced = $credentialData['backupStatus'] === true;
        } else {
            $isSynced = isset($credentialData['backupEligible']) && $credentialData['backupEligible'] === true;
        }

        if ($isSynced) {
            $type .= ' · ' . $t('synced');
        }

        return $type;
    }

    /**
     * Options for the registration ceremony. Options are kept in session and validated on
     *
     * @param erLhcoreClassModelUser $user
     * @param string $name
     * @return array options in a format expected by navigator.credentials.create()
     */
    public static function createRegistrationOptions($user, $name = '')
    {
        if (self::isEnabled() == false) {
            throw new Exception(erTranslationClassLhTranslation::getInstance()->getTranslation('user/passkey', 'Passkeys are not available'));
        }

        if (count(self::getPasskeyList($user->id)) >= self::MAX_PASSKEYS_PER_USER) {
            throw new Exception(erTranslationClassLhTranslation::getInstance()->getTranslation('user/passkey', 'Maximum number of passkeys is reached. Please remove one of the existing passkeys first'));
        }

        $options = PublicKeyCredentialCreationOptions::create(
            PublicKeyCredentialRpEntity::create(self::getRpName(), self::getRpId()),
            PublicKeyCredentialUserEntity::create(
                (string)$user->username,
                self::getUserHandle($user),
                trim($user->name_support) != '' ? trim($user->name_support) : (string)$user->username
            ),
            random_bytes(32),
            array(
                PublicKeyCredentialParameters::createPk(Algorithms::COSE_ALGORITHM_ES256),
                PublicKeyCredentialParameters::createPk(Algorithms::COSE_ALGORITHM_RS256),
            ),
            AuthenticatorSelectionCriteria::create(
                null,
                AuthenticatorSelectionCriteria::USER_VERIFICATION_REQUIREMENT_REQUIRED,
                AuthenticatorSelectionCriteria::RESIDENT_KEY_REQUIREMENT_REQUIRED
            ),
            'none',
            self::getCredentialDescriptors($user->id),
            self::CEREMONY_TIMEOUT
        );

        $optionsJson = self::getSerializer()->serialize($options, 'json');

        $_SESSION[self::SESSION_REGISTRATION] = array(
            'created_at' => time(),
            'user_id' => (int)$user->id,
            'name' => self::sanitizeName($name),
            'options' => $optionsJson
        );

        return json_decode($optionsJson, true);
    }

    /**
     * Validates the registration ceremony and stores the credential
     *
     * @param erLhcoreClassModelUser $user
     * @param array $responseData PublicKeyCredential JSON representation
     * @return erLhcoreClassModelUserPasskey
     * @throws Exception
     */
    public static function verifyRegistration($user, $responseData)
    {
        $storedOptions = self::getStoredOptions(self::SESSION_REGISTRATION, (int)$user->id);

        if ($storedOptions === false) {
            throw new Exception(erTranslationClassLhTranslation::getInstance()->getTranslation('user/passkey', 'Registration session has expired, please try again'));
        }

        $options = self::getSerializer()->deserialize($storedOptions['options'], PublicKeyCredentialCreationOptions::class, 'json');
        $publicKeyCredential = self::getSerializer()->denormalize($responseData, PublicKeyCredential::class, 'json');

        if (!($publicKeyCredential->response instanceof AuthenticatorAttestationResponse)) {
            throw new Exception(erTranslationClassLhTranslation::getInstance()->getTranslation('user/passkey', 'Invalid authenticator response'));
        }

        $credentialRecord = AuthenticatorAttestationResponseValidator::create(
            self::getCeremonyStepManagerFactory()->creationCeremony()
        )->check($publicKeyCredential->response, $options, self::getRpId());

        $existingPasskey = erLhcoreClassModelUserPasskey::findOne(array(
            'filter' => array('credential_id' => self::base64UrlEncode($credentialRecord->publicKeyCredentialId))
        ));

        if ($existingPasskey instanceof erLhcoreClassModelUserPasskey) {
            throw new Exception(erTranslationClassLhTranslation::getInstance()->getTranslation('user/passkey', 'This passkey is already registered'));
        }

        $passkey = new erLhcoreClassModelUserPasskey();
        $passkey->user_id = (int)$user->id;
        $passkey->name = $storedOptions['name'] != '' ? $storedOptions['name'] : 'Passkey ' . date('Y-m-d H:i');
        $passkey->created_at = time();
        $passkey->last_used_at = 0;
        $passkey->setFromCredentialRecord($credentialRecord);
        $passkey->saveThis();

        return $passkey;
    }

    /**
     * Options for the authentication ceremony
     *
     * @param erLhcoreClassModelUser|false $user When user is known only his passkeys are allowed
     * @return array options in a format expected by navigator.credentials.get()
     */
    public static function createAuthenticationOptions($user = null)
    {
        if (self::isEnabled() == false) {
            throw new Exception(erTranslationClassLhTranslation::getInstance()->getTranslation('user/passkey', 'Passkeys are not available'));
        }

        $allowCredentials = $user instanceof erLhcoreClassModelUser ? self::getCredentialDescriptors($user->id) : array();

        $options = PublicKeyCredentialRequestOptions::create(
            random_bytes(32),
            self::getRpId(),
            $allowCredentials,
            PublicKeyCredentialRequestOptions::USER_VERIFICATION_REQUIREMENT_REQUIRED,
            self::CEREMONY_TIMEOUT
        );

        $optionsJson = self::getSerializer()->serialize($options, 'json');

        $_SESSION[self::SESSION_AUTHENTICATION] = array(
            'created_at' => time(),
            'options' => $optionsJson
        );

        return json_decode($optionsJson, true);
    }

    /**
     * Validates the authentication ceremony
     *
     * @param array $responseData PublicKeyCredential JSON representation
     * @return erLhcoreClassModelUser
     * @throws Exception
     */
    public static function verifyAuthentication($responseData)
    {
        $storedOptions = self::getStoredOptions(self::SESSION_AUTHENTICATION);

        if ($storedOptions === false) {
            throw new Exception(erTranslationClassLhTranslation::getInstance()->getTranslation('user/passkey', 'Authentication session has expired, please try again'));
        }

        $options = self::getSerializer()->deserialize($storedOptions['options'], PublicKeyCredentialRequestOptions::class, 'json');
        $publicKeyCredential = self::getSerializer()->denormalize($responseData, PublicKeyCredential::class, 'json');

        if (!($publicKeyCredential->response instanceof AuthenticatorAssertionResponse)) {
            throw new Exception(erTranslationClassLhTranslation::getInstance()->getTranslation('user/passkey', 'Invalid authenticator response'));
        }

        $passkey = erLhcoreClassModelUserPasskey::findOne(array(
            'filter' => array('credential_id' => self::base64UrlEncode($publicKeyCredential->rawId))
        ));

        if (!($passkey instanceof erLhcoreClassModelUserPasskey)) {
            throw new Exception(erTranslationClassLhTranslation::getInstance()->getTranslation('user/passkey', 'Unknown passkey'));
        }

        $updatedCredentialRecord = AuthenticatorAssertionResponseValidator::create(
            self::getCeremonyStepManagerFactory()->requestCeremony()
        )->check(
            $passkey->getCredentialRecord(),
            $publicKeyCredential->response,
            $options,
            self::getRpId(),
            $publicKeyCredential->response->userHandle
        );

        $passkey->setFromCredentialRecord($updatedCredentialRecord);
        $passkey->last_used_at = time();
        $passkey->updateThis();

        $user = erLhcoreClassModelUser::fetch($passkey->user_id);

        if (!($user instanceof erLhcoreClassModelUser)) {
            throw new Exception(erTranslationClassLhTranslation::getInstance()->getTranslation('user/passkey', 'Unknown user'));
        }

        return $user;
    }

    /**
     * Reads and invalidates options stored for the ongoing ceremony
     *
     * @param string $sessionKey
     * @param int|null $userId
     * @return array|false
     */
    private static function getStoredOptions($sessionKey, $userId = null)
    {
        $storedOptions = isset($_SESSION[$sessionKey]) ? $_SESSION[$sessionKey] : null;

        unset($_SESSION[$sessionKey]);

        if (!is_array($storedOptions) || !isset($storedOptions['options']) || !isset($storedOptions['created_at'])) {
            return false;
        }

        if ($storedOptions['created_at'] < time() - self::OPTIONS_TTL) {
            return false;
        }

        if ($userId !== null && (!isset($storedOptions['user_id']) || (int)$storedOptions['user_id'] !== (int)$userId)) {
            return false;
        }

        return $storedOptions;
    }
}

